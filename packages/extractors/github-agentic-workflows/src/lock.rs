//! Whether a workflow's compiled lock file is current: gh-aw writes the
//! hashes of the source it compiled into the lock file's first line
//! (`# gh-aw-metadata: {…}`, `pkg/workflow/compiler_yaml_header.go`), and the
//! extractor recomputes them from the revision ([`crate::hash`]).

use crate::document::Document;
use crate::fields;
use crate::hash::{Read, hashes};
use regex::Regex;
use serde_json::{Value, json};
use std::sync::LazyLock;

static METADATA: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"^#\s*gh-aw-metadata:\s*(\{.+\})\s*$").unwrap());
static LEGACY: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"^#\s*frontmatter-hash:\s*([0-9a-f]{64})\s*$").unwrap());
static BANNER: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"generated by gh-aw \((v[^)\s]+)\)").unwrap());

/// The lock file gh-aw writes beside `<name>.md`.
pub fn lock_path(path: &str) -> String {
    format!("{}.lock.yml", path.strip_suffix(".md").unwrap_or(path))
}

/// What the lock file's header records: the front matter and body hashes, and the compiler's release.
#[derive(Default)]
struct Header {
    frontmatter: Option<String>,
    body: Option<String>,
    compiler: Option<String>,
}

fn header(content: &str) -> Header {
    let mut header = Header::default();
    for line in content.lines().take(64) {
        if let Some(metadata) = METADATA
            .captures(line)
            .and_then(|capture| serde_json::from_str::<Value>(&capture[1]).ok())
        {
            let text = |key: &str| {
                metadata
                    .get(key)
                    .and_then(Value::as_str)
                    .filter(|text| !text.is_empty())
                    .map(str::to_owned)
            };
            header.frontmatter = text("frontmatter_hash");
            header.body = text("body_hash");
            header.compiler = header.compiler.or(text("compiler_version"));
        } else if let Some(hash) = LEGACY.captures(line) {
            header.frontmatter = Some(hash[1].to_owned());
        } else if let Some(version) = BANNER.captures(line) {
            header.compiler = header.compiler.or(Some(version[1].to_owned()));
        }
    }
    header
}

/// A release as `(major, minor, patch)`, or `None` for anything else (such as `dev`).
fn version(text: &str) -> Option<(u64, u64, u64)> {
    let mut parts = text.trim_start_matches('v').split(['.', '-', '+']).map(str::parse::<u64>);
    Some((parts.next()?.ok()?, parts.next()?.ok()?, parts.next()?.ok()?))
}

/// A finding: `{kind, message}`, the message prose with inline code.
pub fn finding(kind: &str, message: String) -> Value {
    json!({"kind": kind, "message": message})
}

/// The workflow's lock: `{path, status, compiler?, body?, reason?}` and its
/// findings. `status` is `current`, `stale` (the front matter or what it
/// imports changed since compiling, so the compiled workflow isn't what the
/// source says), `missing` or `unverified` (no recorded hash, or gh-aw
/// couldn't hash the source either). `body` is `changed` when only the
/// prompt changed: gh-aw reads it when the workflow runs, so that is stale
/// only with `on.stale-check: full`.
pub fn lock(path: &str, document: &Document, inlined: bool, full_check: bool, read: Read) -> (Value, Vec<Value>) {
    let lock = lock_path(path);
    let name = lock.rsplit('/').next().unwrap_or(&lock).to_owned();
    let Some(content) = read(&lock) else {
        let message = format!("`{name}` is missing: compile the workflow with `gh aw compile`.");
        return (json!({"path": lock, "status": "missing"}), vec![finding("lock-missing", message)]);
    };
    let header = header(&content);
    let mut data = json!({"path": lock});
    let mut findings = Vec::new();
    if let Some(compiler) = &header.compiler {
        data["compiler"] = json!(compiler);
        if let (Some(compiled), Some(known)) = (version(compiler), version(fields::release()))
            && compiled > known
        {
            findings.push(finding(
                "newer-compiler",
                format!(
                    "Compiled by gh-aw `{compiler}`, newer than `{}`, the release whose front matter this extractor knows: fields it doesn't know are listed as unrecognized.",
                    fields::release()
                ),
            ));
        }
    }
    let Some(recorded) = header.frontmatter else {
        data["status"] = json!("unverified");
        data["reason"] = json!("its header records no front matter hash");
        findings.push(finding(
            "lock-unverified",
            format!("Whether `{name}` is current can't be told: it records no source hash."),
        ));
        return (data, findings);
    };
    match hashes(path, document, inlined, read) {
        Err(reason) => {
            data["status"] = json!("unverified");
            data["reason"] = json!(reason);
            findings.push(finding(
                "lock-unverified",
                format!("Whether `{name}` is current can't be told: {reason}."),
            ));
        }
        Ok(computed) => {
            let body_changed = header.body.as_ref().is_some_and(|body| *body != computed.body);
            if body_changed {
                data["body"] = json!("changed");
            }
            if recorded != computed.frontmatter || (body_changed && full_check) {
                data["status"] = json!("stale");
                let what = if recorded != computed.frontmatter {
                    "its front matter or imports changed"
                } else {
                    "its prompt changed"
                };
                findings.push(finding(
                    "lock-stale",
                    format!("`{name}` is stale: {what} since it was compiled; run `gh aw compile`."),
                ));
            } else {
                data["status"] = json!("current");
            }
        }
    }
    (data, findings)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_the_header_and_compares_releases() {
        let content = "# gh-aw-metadata: {\"schema_version\":\"v4\",\"frontmatter_hash\":\"aa\",\"body_hash\":\"bb\",\"compiler_version\":\"v0.93.3\"}\n# gh-aw-manifest: {}\n# This file was automatically generated by gh-aw (v0.93.3). DO NOT EDIT.\n";
        let header = header(content);
        assert_eq!(header.frontmatter.as_deref(), Some("aa"));
        assert_eq!(header.body.as_deref(), Some("bb"));
        assert_eq!(header.compiler.as_deref(), Some("v0.93.3"));
        assert!(version("v1.10.0") > version("v1.3.0"));
        assert_eq!(version("dev"), None);
        assert_eq!(lock_path(".github/workflows/a.md"), ".github/workflows/a.lock.yml");
    }
}
