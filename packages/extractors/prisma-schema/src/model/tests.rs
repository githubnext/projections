use super::datetime::rfc3339;

#[test]
fn normalizes_rfc3339_like_prisma() {
    let cases = [
        ("2020-01-01T00:00:00Z", "2020-01-01T00:00:00+00:00"),
        ("2020-01-01t00:00:00.5z", "2020-01-01T00:00:00.500+00:00"),
        ("2020-01-01 10:00:00.123456-07:00", "2020-01-01T10:00:00.123456-07:00"),
        ("2024-02-29T00:00:00.0000000011+05:30", "2024-02-29T00:00:00.000000001+05:30"),
        ("2020-01-01T00:00:00-00:00", "2020-01-01T00:00:00+00:00"),
    ];
    for (input, expected) in cases {
        assert_eq!(rfc3339(input).as_deref(), Some(expected), "{input}");
    }
    for invalid in [
        "2023-02-29T00:00:00Z",
        "2020-01-01",
        "2020-01-01T00:00:00",
        "2020-13-01T00:00:00Z",
        "2020-01-01T00:00:00.Z",
    ] {
        assert_eq!(rfc3339(invalid), None, "{invalid}");
    }
}
