import {useState, type ReactNode} from 'react'
import {Activity, Sparkle} from 'lucide-react'
import type {WordRun} from '@githubnext/projections-renderer-sdk/presentation'
import {generatedForm, type GeneratedField} from '../../details/generated.js'
import {Prose} from '../prose.js'
import {cn} from '../lib/utils.js'

const generatedToggle =
  'ph-generated-toggle pj:rounded-md pj:border pj:bg-transparent pj:px-1.5 pj:text-xs pj:text-muted-foreground pj:hover:text-foreground pj:focus-visible:outline-hidden pj:focus-visible:ring-2 pj:focus-visible:ring-ring/50 pj:aria-pressed:border-foreground/40 pj:aria-pressed:text-foreground'

/** Two layouts in one grid cell, the inactive one hidden, so a toggle never moves what follows. */
function Stack({active, first, second}: {active: 0 | 1; first: ReactNode; second: ReactNode}) {
  return (
    <div className="ph-generated-stack pj:grid">
      {[first, second].map((layer, index) => (
        <div
          key={index}
          className={cn('pj:col-start-1 pj:row-start-1 pj:min-w-0', active !== index && 'pj:invisible')}
          aria-hidden={active !== index || undefined}
          data-active={active === index || undefined}
        >
          {layer}
        </div>
      ))}
    </div>
  )
}

/** A generated value's word diff: removed words struck, added ones underlined away. */
function WordDiff({runs}: {runs: WordRun[]}) {
  return (
    <p className="ph-generated-diff pj:text-xs pj:break-words pj:whitespace-pre-wrap" data-word-diff="">
      {runs.map((run, index) =>
        run.op === 'same' ? (
          <span key={index}>{run.text}</span>
        ) : run.op === 'removed' ? (
          <del key={index} className="pj:rounded-sm pj:bg-removed-muted">
            {run.text}
          </del>
        ) : (
          <ins key={index} className="pj:rounded-sm pj:bg-added-muted pj:no-underline">
            {run.text}
          </ins>
        ),
      )}
    </p>
  )
}

function Passage({text, json, side}: {text: string | undefined; json: boolean; side?: 'before' | 'after'}) {
  return (
    <p
      className={cn(
        'ph-generated-passage pj:min-w-0 pj:text-xs pj:break-words pj:whitespace-pre-wrap',
        json && 'pj:font-mono',
        text === undefined && 'pj:text-muted-foreground',
      )}
      data-side={side}
    >
      {text ?? 'None'}
    </p>
  )
}

/**
 * One generated value (`RowDetails.generated`): its name, the quiet Generated mark and its value. Regenerated from
 * the same inputs, After's text with the neutral volatile icon, "Regenerated from the same inputs" and a toggle for
 * Before's wording; regenerated because its basis moved, why, and both passages side by side with a word diff toggle.
 * Toggles swap layers of one grid cell, so nothing shifts.
 */
export function GeneratedValue({field}: {field: GeneratedField}) {
  const [shown, setShown] = useState(false)
  const form = generatedForm(field)
  const pair = (
    <div className="ph-generated-pair pj:grid pj:grid-cols-[repeat(auto-fit,minmax(min(100%,10rem),1fr))] pj:gap-1.5">
      {(['before', 'after'] as const).map(side => (
        <div key={side} className="pj:flex pj:min-w-0 pj:flex-col pj:gap-0.5 pj:rounded-md pj:border pj:px-2 pj:py-1.5">
          <span className="pj:text-xs pj:text-muted-foreground">{side === 'before' ? 'Before' : 'After'}</span>
          <Passage text={form[side]} json={form.json} side={side} />
        </div>
      ))}
    </div>
  )
  return (
    <li
      className="ph-generated pj:flex pj:min-w-0 pj:flex-col pj:gap-1 pj:px-2 pj:py-1.5"
      data-generated={form.form}
      data-generated-path={field.path}
    >
      <span className="pj:flex pj:min-w-0 pj:items-baseline pj:gap-2 pj:text-xs">
        <code className="ph-field-name pj:break-all pj:font-mono pj:text-muted-foreground">{field.name}</code>
        <span
          className="ph-generated-mark pj:inline-flex pj:items-baseline pj:gap-1 pj:text-muted-foreground"
          data-generated-mark=""
          title="Generated by the extractor (for example by a language model), not extracted from the code"
        >
          <Sparkle aria-hidden="true" className="pj:size-3 pj:shrink-0 pj:self-center" />
          Generated
        </span>
      </span>
      {form.form === 'plain' && <Passage text={form.after ?? form.before} json={form.json} />}
      {form.form === 'regenerated' && (
        <>
          <Stack
            active={shown ? 1 : 0}
            first={<Passage text={form.after} json={form.json} side="after" />}
            second={<Passage text={form.before} json={form.json} side="before" />}
          />
          <span className="pj:flex pj:flex-wrap pj:items-center pj:justify-between pj:gap-1.5 pj:text-xs pj:text-muted-foreground">
            <span className="ph-generated-why pj:inline-flex pj:items-baseline pj:gap-1">
              <Activity aria-hidden="true" className="pj:size-3 pj:shrink-0 pj:self-center" />
              <Prose>{form.words!}</Prose>
            </span>
            <button type="button" className={generatedToggle} aria-pressed={shown} onClick={() => setShown(!shown)}>
              {shown ? "After's wording" : "Before's wording"}
            </button>
          </span>
        </>
      )}
      {form.form === 'changed' && (
        <>
          <span className="ph-generated-why pj:text-xs pj:text-muted-foreground">
            <Prose>{form.words!}</Prose>
          </span>
          {form.same ? (
            <Passage text={form.after} json={form.json} />
          ) : form.runs ? (
            <Stack active={shown ? 1 : 0} first={pair} second={<WordDiff runs={form.runs} />} />
          ) : (
            pair
          )}
          {form.runs && (
            <span className="pj:flex">
              <button type="button" className={generatedToggle} aria-pressed={shown} onClick={() => setShown(!shown)}>
                Word diff
              </button>
            </span>
          )}
        </>
      )}
    </li>
  )
}

/** A detail card's generated values (`RowDetails.generated`), first among its fields. */
export function GeneratedList({generated, className}: {generated: readonly GeneratedField[]; className?: string}) {
  if (!generated.length) return null
  return (
    <ul
      className={cn(
        'ph-generated-fields pj:-mx-1 pj:flex pj:min-w-0 pj:flex-col pj:overflow-hidden pj:rounded-md pj:border pj:[&>li+li]:border-t',
        className,
      )}
      aria-label="Generated values"
    >
      {generated.map(field => (
        <GeneratedValue key={field.path} field={field} />
      ))}
    </ul>
  )
}
