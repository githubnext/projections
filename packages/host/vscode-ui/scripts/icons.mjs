// Writes src/icons.generated.ts: the renderer icon vocabulary as codicons (@vscode/codicons, whose icons are licensed
// CC BY 4.0 by Microsoft; see THIRD_PARTY_NOTICES.md), so renderer icons match the VS Code UI around them. The
// projection parts are Projections' own icons (brand/parts, drawn at codicon weight), as the extension's are, and the
// badge icons (badgeIconNames) are the SDK's badge glyphs: an icon set's glyph scaled into a disc has neither its
// stroke nor its centre, so every host cuts the same glyphs, one stroke, centred.
//   node scripts/icons.mjs
import {readFileSync, writeFileSync} from 'node:fs'
import {createRequire} from 'node:module'
import {dirname, join} from 'node:path'
import {badgeIconNames, defaultThemeTokens, iconNames, iconToken, svgIconValue} from '@githubnext/projections-renderer-sdk/protocol'

const require = createRequire(import.meta.url)
const codicons = join(dirname(require.resolve('@vscode/codicons/package.json')), 'src', 'icons')
/** The codicon drawn for each outline icon in the vocabulary (every name but the badges). */
const map = {
  warning: 'warning',
  error: 'error',
  info: 'info',
  unknown: 'question',
  additive: 'diff-added',
  compatible: 'pass',
  enforced: 'workspace-trusted',
  unenforced: 'workspace-untrusted',
  include: 'diff-added',
  exclude: 'circle-slash',
  visible: 'eye',
  hidden: 'eye-closed',
  expand: 'screen-full',
  collapse: 'screen-normal',
  rescoped: 'arrow-swap',
  settings: 'settings',
  agent: 'chip',
  varied: 'pulse',
  generated: 'sparkle',
  host: 'server',
  policy: 'shield',
  workload: 'package',
  credential: 'key',
  process: 'terminal',
  file: 'file',
  network: 'globe',
  module: 'extensions',
  bytecode: 'file-binary',
  namespace: 'layers',
  application: 'window',
  other: 'ellipsis',
  extractor: 'part:extractor',
  comparator: 'part:comparator',
  renderer: 'part:renderer',
}
/** Codicons drawn here: the sparkle codicon's own drawing exceeds an icon token's length, so its single four-point star, in outline, at codicon weight. */
const custom = {
  sparkle:
    '<path d="M8 2.5C8.35 5.6 10.4 7.65 13.5 8C10.4 8.35 8.35 10.4 8 13.5C7.65 10.4 5.6 8.35 2.5 8C5.6 7.65 7.65 5.6 8 2.5Z" fill="none" stroke="#000" stroke-width="1.2" stroke-linejoin="round"/>',
}
/** A codicon's drawing: its SVG's children, filled black (the renderer draws the icon as a mask in `currentColor`). */
function drawing(name) {
  if (custom[name]) return custom[name]
  if (name.startsWith('part:')) {
    const part = readFileSync(new URL(`../../../../brand/parts/${name.slice('part:'.length)}.svg`, import.meta.url), 'utf8')
    return /<svg[^>]*>([\s\S]*)<\/svg>/u.exec(part)[1].replaceAll('currentColor', '#000')
  }
  const svg = readFileSync(join(codicons, `${name}.svg`), 'utf8')
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/u.exec(svg)?.[1]
  if (!inner) throw new Error(`Unreadable codicon ${name}`)
  return `<g fill="#000">${inner.trim()}</g>`
}
const badges = defaultThemeTokens('dark')
const lines = iconNames.map(name => {
  if (badgeIconNames.includes(name)) return `  'icon-${name}': ${JSON.stringify(badges[iconToken(name)])},`
  if (!map[name]) throw new Error(`No codicon for ${name}`)
  const value = svgIconValue(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">${drawing(map[name])}</svg>`)
  return `  'icon-${name}': ${JSON.stringify(value)},`
})
const version = require('@vscode/codicons/package.json').version
writeFileSync(
  new URL('../src/icons.generated.ts', import.meta.url),
  `// Generated by scripts/icons.mjs from @vscode/codicons ${version} (icons CC BY 4.0, Copyright (c) Microsoft Corporation); don't edit.
import type {IconTokenName} from '@githubnext/projections-host'

/** The renderer icon vocabulary as codicons, by theme token; the badge icons are the SDK's badge glyphs. */
export const codiconTokens: Record<IconTokenName, string> = {
${lines.join('\n')}
}

/** The codicon each outline renderer icon is drawn with (\`part:<name>\` is the projection part's own icon, brand/parts); the badge icons are the SDK's badge glyphs. */
export const codiconNames: Record<string, string> = ${JSON.stringify(map, null, 2)
    .replace(/"([a-z-]+)":/gu, (_, key) => (/-/u.test(key) ? `'${key}':` : `${key}:`))
    .replaceAll('"', "'")}
`,
)
