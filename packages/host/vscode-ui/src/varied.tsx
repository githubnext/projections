import {useState} from 'react'
import type {ReactNode} from 'react'
import {generatedForm} from '@githubnext/projections-host'
import type {GeneratedField, VariedField} from '@githubnext/projections-host'
import {uiCodicons} from './codicons.js'
import {Prose} from './prose.js'

const short = (text: string) => (text.length > 160 ? `${text.slice(0, 157)}…` : text)

/**
 * The volatile values of a change that differ (`RowDetails.varied`), neutrally: each path and its values in the
 * editor's monospace font, old → new, and whether it stayed within tolerance ("durationMs 120 → 135", "within
 * tolerance") or went beyond it ("beyond tolerance (volatile)", with the pulse codicon), plus the comparison's reason
 * when it gives one. The parts are set apart by the row's gap, not a separator character, so a wrapped row never
 * starts a line with one; assistive technology hears a comma. No change colors: a value within tolerance is not a
 * change.
 */
export function VariedList({varied}: {varied: readonly VariedField[]}) {
  if (!varied.length) return null
  return (
    <div className="phv-varied">
      <p className="phv-muted phv-varied-heading">Volatile values</p>
      <ul className="phv-varied-fields" aria-label="Volatile values">
        {varied.map(field => (
          <li key={field.path} className="phv-varied-field" data-varied-path={field.path} data-within={field.within}>
            <code className="phv-varied-name">{field.name}</code>
            <span className="phv-varied-values" title={`${field.before ?? '—'} → ${field.after ?? '—'}`}>
              <span className="phv-visually-hidden">was </span>
              {short(field.before ?? '—')}
              <span aria-hidden="true" className="phv-value-arrow">
                {' → '}
              </span>
              <span className="phv-visually-hidden">, now </span>
              {short(field.after ?? '—')}
            </span>
            <span className="phv-varied-words">
              <span className="phv-visually-hidden">, </span>
              {!field.within && <span className={`codicon codicon-${uiCodicons.varied}`} aria-hidden="true" />}
              {field.words}
            </span>
            {field.reason && <span className="phv-varied-reason">{field.reason}</span>}
          </li>
        ))}
      </ul>
    </div>
  )
}

const generatedTitle = 'Generated by the extractor (for example by a language model), not extracted from the code'

/** Two layouts in one grid cell, the inactive one hidden, so a toggle never moves what follows. */
function Stack({active, first, second}: {active: 0 | 1; first: ReactNode; second: ReactNode}) {
  return (
    <div className="phv-generated-stack">
      {[first, second].map((layer, index) => (
        <div
          key={index}
          className="phv-generated-layer"
          aria-hidden={active !== index || undefined}
          data-active={active === index || undefined}
        >
          {layer}
        </div>
      ))}
    </div>
  )
}

function Passage({text, json, side}: {text: string | undefined; json: boolean; side?: 'before' | 'after'}) {
  return (
    <p className={`phv-generated-passage${json ? ' phv-generated-json' : ''}${text === undefined ? ' phv-muted' : ''}`} data-side={side}>
      {text ?? 'None'}
    </p>
  )
}

/**
 * One generated value (`RowDetails.generated`), in VS Code's hover style: its name, the quiet Generated mark (the
 * sparkle codicon) and its value. Regenerated from the same inputs, After's text with the pulse codicon, "Regenerated
 * from the same inputs" and a toggle for Before's wording; regenerated because its basis moved, why, and both passages
 * side by side with a word diff toggle. Toggles swap layers of one grid cell, so nothing shifts.
 */
export function GeneratedValue({field}: {field: GeneratedField}) {
  const [shown, setShown] = useState(false)
  const form = generatedForm(field)
  const pair = (
    <div className="phv-generated-pair">
      {(['before', 'after'] as const).map(side => (
        <div key={side} className="phv-generated-side">
          <span className="phv-muted">{side === 'before' ? 'Before' : 'After'}</span>
          <Passage text={form[side]} json={form.json} side={side} />
        </div>
      ))}
    </div>
  )
  const toggle = (label: string) => (
    <button type="button" className="phv-generated-toggle" aria-pressed={shown} onClick={() => setShown(!shown)}>
      {label}
    </button>
  )
  return (
    <li className="phv-generated" data-generated={form.form} data-generated-path={field.path}>
      <span className="phv-generated-label">
        <code className="phv-varied-name">{field.name}</code>
        <span className="phv-generated-mark" data-generated-mark="" title={generatedTitle}>
          <span className={`codicon codicon-${uiCodicons.generated}`} aria-hidden="true" />
          Generated
        </span>
      </span>
      {form.form === 'plain' && <Passage text={form.after ?? form.before} json={form.json} />}
      {form.form === 'regenerated' && (
        <>
          <Stack
            active={shown ? 1 : 0}
            first={<Passage text={form.after} json={form.json} side="after" />}
            second={<Passage text={form.before} json={form.json} side="before" />}
          />
          <span className="phv-generated-note">
            <span className="phv-varied-words phv-generated-why">
              <span className={`codicon codicon-${uiCodicons.varied}`} aria-hidden="true" />
              <Prose>{form.words!}</Prose>
            </span>
            {toggle(shown ? "After's wording" : "Before's wording")}
          </span>
        </>
      )}
      {form.form === 'changed' && (
        <>
          <span className="phv-muted phv-generated-why">
            <Prose>{form.words!}</Prose>
          </span>
          {form.same ? (
            <Passage text={form.after} json={form.json} />
          ) : form.runs ? (
            <Stack
              active={shown ? 1 : 0}
              first={pair}
              second={
                <p className="phv-generated-passage phv-generated-diff" data-word-diff="">
                  {form.runs.map((run, index) =>
                    run.op === 'same' ? (
                      <span key={index}>{run.text}</span>
                    ) : run.op === 'removed' ? (
                      <del key={index}>{run.text}</del>
                    ) : (
                      <ins key={index}>{run.text}</ins>
                    ),
                  )}
                </p>
              }
            />
          ) : (
            pair
          )}
          {form.runs && <span className="phv-generated-note">{toggle('Word diff')}</span>}
        </>
      )}
    </li>
  )
}

/** A detail card's generated values (`RowDetails.generated`), first among its fields. */
export function GeneratedList({generated}: {generated: readonly GeneratedField[]}) {
  if (!generated.length) return null
  return (
    <ul className="phv-varied-fields phv-generated-fields" aria-label="Generated values">
      {generated.map(field => (
        <GeneratedValue key={field.path} field={field} />
      ))}
    </ul>
  )
}
