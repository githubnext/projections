import {test} from 'node:test'
import assert from 'node:assert/strict'
import {createElement} from 'react'
import {renderToStaticMarkup} from 'react-dom/server'
import {GeneratedMark, GeneratedText} from '../dist/react.js'

const html = element => renderToStaticMarkup(element)

test('every generated field carries the quiet Generated mark and its name in mono', () => {
  const markup = html(createElement(GeneratedText, {name: 'summary', after: 'Holds a cart.'}))
  assert.match(markup, /data-generated-mark=""/u)
  assert.match(markup, /data-icon="generated"/u)
  assert.match(markup, />Generated</u)
  assert.match(markup, /class="pk-generated-name" data-projections-identifier=""[^>]*>summary</u)
  assert.match(markup, /Holds a cart\./u)
  assert.match(html(createElement(GeneratedMark)), /title="Generated by the extractor/u)
})

test("rewording from the same inputs shows After's text, a neutral note and Before's wording one toggle away", () => {
  const markup = html(
    createElement(GeneratedText, {
      name: 'summary',
      before: 'Validates orders.',
      after: 'Checks orders.',
      entry: {within: true, generated: true},
    }),
  )
  assert.match(markup, /data-generated="regenerated"/u)
  assert.match(markup, /data-icon="varied"/u)
  assert.match(markup, /Regenerated from the same inputs/u)
  assert.match(markup, /aria-pressed="false"[^>]*>Before&#x27;s wording/u)
  // Both wordings share one grid cell; Before's is hidden, After's shown; never a word diff.
  assert.match(markup, /data-active="true"><div class="pk-generated-passage" data-side="after">Checks orders\./u)
  assert.match(markup, /aria-hidden="true"><div class="pk-generated-passage" data-side="before">Validates orders\./u)
  assert.doesNotMatch(markup, /<del|<ins|Word diff/u)
})

test('a changed basis shows why and both passages, with a word diff a toggle away', () => {
  const markup = html(
    createElement(GeneratedText, {
      name: 'summary',
      before: 'Holds a cart.',
      after: 'Holds a cart and its total.',
      entry: {within: false, generated: true, because: ['input']},
    }),
  )
  assert.match(markup, /data-generated="changed"/u)
  assert.match(markup, /Regenerated because the input changed/u)
  assert.match(markup, />Before<.*>Holds a cart\.<.*>After<.*>Holds a cart and its total\.</su)
  assert.match(markup, /<ins class="pk-generated-added"> and its total<\/ins>/u)
  assert.match(markup, /aria-pressed="false"[^>]*>Word diff/u)
  const json = html(
    createElement(GeneratedText, {name: 'tags', before: ['a'], after: ['b'], entry: {within: false, generated: true, because: ['model']}}),
  )
  assert.match(json, /pk-generated-json/u)
  assert.doesNotMatch(json, /Word diff/u)
  const same = html(
    createElement(GeneratedText, {
      name: 'summary',
      before: 'Same.',
      after: 'Same.',
      entry: {within: false, generated: true, because: ['input']},
    }),
  )
  assert.match(same, /the wording is the same/u)
})
