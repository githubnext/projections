// Generated values in presentation: which of an item's values an extraction declares generated, how a regenerated
// value's change reads, and (word-diff.ts) a word diff for the optional comparison of two passages. See
// docs/design/generated-values.md.
import type {Varied} from '@githubnext/projections-schemas'

/** The accessible name and visible word of the mark every generated field carries. */
export const generatedLabel = 'Generated'

/** What the mark means, for its title. */
export const generatedTitle = 'Generated by the extractor (for example by a language model), not extracted from the code'

/** A row with the comparison's status and volatile values. */
interface VariedRow {
  status?: string | undefined
  varied?: readonly Varied[] | undefined
}

/**
 * Whether a change only regenerated generated values from the same inputs: `unchanged`, with a generated `varied`
 * entry. Like any variation within tolerance it is presented as unchanged; hosts count it as "regenerated".
 */
export function regenerated(change: VariedRow): boolean {
  return change.status === 'unchanged' && Boolean(change.varied?.some(entry => entry.generated))
}

/**
 * Whether a change is `unchanged` with a volatile value other than a generated one varied within its tolerance,
 * such as a duration: what hosts count as "varied within tolerance".
 */
export function variedWithinTolerance(change: VariedRow): boolean {
  return change.status === 'unchanged' && Boolean(change.varied?.some(entry => !entry.generated))
}

/** The volatile declarations an extraction makes, as far as generated values need them. */
interface Declaration {
  collection?: string
  kinds?: readonly string[]
  path: string
  generated?: boolean
  basis?: string
}

const segments = (pointer: string) =>
  pointer
    .split('/')
    .slice(1)
    .map(segment => segment.replace(/~1/g, '/').replace(/~0/g, '~'))
const escape = (segment: string) => segment.replace(/~/g, '~0').replace(/\//g, '~1')

function child(value: unknown, key: string): unknown {
  if (Array.isArray(value)) return /^(0|[1-9][0-9]*)$/.test(key) ? value[Number(key)] : undefined
  if (value !== null && typeof value === 'object' && Object.hasOwn(value, key)) return (value as Record<string, unknown>)[key]
  return undefined
}

/** Every concrete pointer a declared path matches in `item`, with the keys its `*` segments took. */
function expand(item: unknown, pattern: readonly string[], path = '', bound: string[] = []): [string, string[]][] {
  if (item === undefined) return []
  if (!pattern.length) return [[path, bound]]
  const [head, ...rest] = pattern
  if (head !== '*') return expand(child(item, head!), rest, `${path}/${escape(head!)}`, bound)
  const keys = Array.isArray(item)
    ? item.map((_, index) => String(index))
    : item !== null && typeof item === 'object'
      ? Object.keys(item)
      : []
  return keys.flatMap(key => expand(child(item, key), rest, `${path}/${escape(key)}`, [...bound, key]))
}

function render(pattern: readonly string[], bound: readonly string[]): string {
  let next = 0
  return pattern.map(segment => `/${escape(segment === '*' ? (bound[next++] ?? '*') : segment)}`).join('')
}

/** One generated value of an item: its concrete pointer, and its basis's. */
export interface GeneratedPath {
  /** The generated value's RFC 6901 pointer into the item, under `/data/`, with wildcards bound. */
  path: string
  /** The pointer to the basis it was generated from, with the same wildcards bound. */
  basis: string
}

/**
 * An item's generated values, from the extraction's `volatile` declarations: each concrete pointer (under `/data/`)
 * a generated declaration matches, with the pointer of its basis. Hosts and renderers mark these fields Generated.
 */
export function generatedPaths(
  extraction: {readonly volatile?: readonly Declaration[] | undefined},
  item: {readonly kind?: string; readonly [key: string]: unknown} | undefined,
  collection: 'entities' | 'relationships' = 'entities',
): GeneratedPath[] {
  if (!item) return []
  const found = new Map<string, string>()
  for (const declaration of extraction.volatile ?? []) {
    if (!declaration.generated || !declaration.basis) continue
    if ((declaration.collection ?? 'entities') !== collection) continue
    if (declaration.kinds && !declaration.kinds.includes(String(item.kind))) continue
    const basis = segments(declaration.basis)
    for (const [path, bound] of expand(item, segments(declaration.path))) found.set(path, render(basis, bound))
  }
  return [...found].map(([path, basis]) => ({path, basis})).toSorted((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))
}

/** A basis value as the extraction records it: named parts. */
export type BasisValue = Readonly<Record<string, string>>

const hashed = (value: string | undefined) => value === undefined || value.startsWith('sha256:')

/** A basis part's change in words: `the input`, or `` `context` `` for a part without a word of its own. */
function partWords(part: string, before: BasisValue | undefined, after: BasisValue | undefined): string {
  const name = ['input', 'prompt', 'model'].includes(part) ? `the ${part}` : `\`${part.replace(/[\x60\\]/g, '\\$&')}\``
  const [old, next] = [before?.[part], after?.[part]]
  if (old !== undefined && next !== undefined && !hashed(old) && !hashed(next)) {
    const code = (text: string) => `\`${text.replace(/[\x60\\]/g, '\\$&')}\``
    return `${name} (${code(old)} → ${code(next)})`
  }
  return name
}

/**
 * Why a generated value differs, as protocol prose (code in backtick spans; render it with the kit's `Prose`):
 * "Regenerated from the same inputs" when the bases are equal, "Regenerated because the input and the prompt
 * changed" when parts moved (a verbatim part, such as a model ID, with its old and new values), "Generated only
 * after" for a value on one side only. With the bases, a moved model reads "the model (`a@1` → `a@2`)".
 */
export function generatedWords(
  entry: Pick<Varied, 'within' | 'because' | 'reason'>,
  bases?: {before?: BasisValue; after?: BasisValue},
): string {
  if (entry.reason) return entry.reason
  const because = entry.because ?? []
  if (!because.length) return 'Regenerated from the same inputs'
  const words = because.map(part => partWords(part, bases?.before, bases?.after))
  const list = words.length === 1 ? words[0] : `${words.slice(0, -1).join(', ')} and ${words.at(-1)}`
  return `Regenerated because ${list} changed`
}

/** A generated value as text: a string as it is, anything else as indented JSON. */
export function generatedText(value: unknown): string {
  if (typeof value === 'string') return value
  if (value === undefined) return ''
  return JSON.stringify(value, null, 2)
}
