/**
 * The name of a theme token in the current set (`themeTokenNames`), without its `--projections-` prefix: a color,
 * spacing, type, radius, shadow or control size token, or an icon token (`icon-<name>`).
 */
export type ThemeTokenName = keyof typeof definitions | IconTokenName

/** Every token name in the current token set. */
export const themeTokenNames = [...Object.keys(definitions), ...iconNames.map(iconToken)] as ThemeTokenName[]

/**
 * Layout tokens a host may send that have no default (`resolveThemeTokens` leaves them undefined), so a renderer reads
 * each with its own value as the fallback: `stage-inset`, the inline space between the frame's edges and its content,
 * and `stage-max-height`, the most a content-sized stage that pans and zooms asks for (`px`, or `vh` of the host's window).
 */
export const optionalThemeTokenNames = ['stage-inset', 'stage-max-height'] as const

/** The default value of every token for a color mode. */
export function defaultThemeTokens(colorMode: ColorMode): Record<ThemeTokenName, string> {
  const index = colorMode === 'dark' ? 1 : 0
  return {
    ...(Object.fromEntries(Object.entries(definitions).map(([name, values]) => [name, values[index]])) as Record<
      keyof typeof definitions,
      string
    >),
    ...defaultIconTokens,
  }
}

/** A host's tokens over the defaults, so every token of the current set is defined. */
export function resolveThemeTokens(theme: {colorMode: ColorMode; tokens: {[name: string]: string}}): Record<string, string> {
  return {...defaultThemeTokens(theme.colorMode), ...theme.tokens}
}

type Suffix<Name, Prefix extends string> = Name extends `${Prefix}${infer Rest}` ? Rest : never
/** Color token names without `color-`, such as `fg-muted` or `added-border`. */
export type ColorTokenName = Suffix<keyof typeof definitions, 'color-'>
/** Steps of the space scale: `space-1` (4px) to `space-8` (48px). */
export type SpaceStep = 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8
/** Steps of the type scale: `xs` (12px) to `xl` (20px); `md` is the body size, the `font-size` token. */
export type FontSizeStep = 'xs' | 'sm' | 'md' | 'lg' | 'xl'
/** Steps of the corner radius scale: `sm` (6px) to `lg` (10px), and `full` for pills; `md` is the `radius` token. */
export type RadiusStep = 'sm' | 'md' | 'lg' | 'full'
/** Font weights: `normal` (400), `medium` (500), `semibold` (600) and `bold` (700). */
export type FontWeightStep = 'normal' | 'medium' | 'semibold' | 'bold'

/** `var(--projections-<name>)`: a theme token as a CSS value, for the rare inline style. */
export function tokenVar(name: ThemeTokenName): string {
  return `var(--projections-${name})`
}

/**
 * Theme tokens as CSS values, typed so a name that isn't a token doesn't compile. Prefer the kit's components and
 * their props; use these for an inline style the kit doesn't cover, such as `style={{gap: token.space(2)}}`. The
 * renderer checks (`palette`, `type-scale`, `spacing`) hold every painted value to these.
 */
export const token = {
  var: tokenVar,
  color: (name: ColorTokenName): string => tokenVar(`color-${name}` as ThemeTokenName),
  /** A categorical palette color, `chart-1` to `chart-16`, for parts marked `data-projections-category`. */
  chart: (index: number): string => tokenVar(`chart-${(((Math.trunc(index) % 16) + 16) % 16) + 1}` as ThemeTokenName),
  space: (step: SpaceStep): string => tokenVar(`space-${step}`),
  fontSize: (step: FontSizeStep): string => tokenVar(step === 'md' ? 'font-size' : `font-size-${step}`),
  fontWeight: (step: FontWeightStep): string => tokenVar(`font-weight-${step}`),
  radius: (step: RadiusStep): string => tokenVar(step === 'md' ? 'radius' : `radius-${step}`),
} as const
