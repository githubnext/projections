// Writes packages/cli/node/extractor.mjs: `@githubnext/projections/extractor` (src/extractor.ts) bundled into one
// dependency-free module, which the CLI embeds and gives custom extractors run with `node` (packages/cli/src/node.rs),
// so they need nothing installed. `--check` fails instead when the committed file differs.
import {execFileSync} from 'node:child_process'
import {mkdtempSync, readFileSync, rmSync, writeFileSync} from 'node:fs'
import {createRequire} from 'node:module'
import {tmpdir} from 'node:os'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'
import {build} from 'tsdown'

const check = process.argv.includes('--check')
const sdk = join(dirname(fileURLToPath(import.meta.url)), '..')
const repository = join(sdk, '../..')
const target = join(repository, 'packages/cli/node/extractor.mjs')
const header = `// Generated by packages/sdk/scripts/extractor-module.mjs from packages/sdk/src/extractor.ts; don't edit it.
// \`@githubnext/projections/extractor\` as one module, which the runner gives custom extractors run with \`node\`.
`

const output = mkdtempSync(join(tmpdir(), 'projections-extractor-module-'))
let bundled
try {
  await build({
    config: false,
    cwd: sdk,
    entry: {extractor: 'src/extractor.ts'},
    outDir: output,
    format: 'esm',
    platform: 'node',
    target: 'node20',
    dts: false,
    hash: false,
    fixedExtension: true,
    sourcemap: false,
    treeshake: true,
    tsconfig: 'tsconfig.json',
    publint: false,
    attw: false,
    logLevel: 'warn',
  })
  // The bundler names each source module in a comment, with the platform's separators.
  bundled = readFileSync(join(output, 'extractor.mjs'), 'utf8').replace(/^\/\/ src\\.*$/gm, line => line.replaceAll('\\', '/'))
} finally {
  rmSync(output, {recursive: true, force: true})
}
if (/^\s*import\s.*from\s+['"](?!node:)/m.test(bundled)) throw new Error('The extractor module must import only node: built-ins')

const oxfmt = join(dirname(createRequire(import.meta.url).resolve('oxfmt/package.json')), 'bin/oxfmt')
const text = execFileSync(process.execPath, [oxfmt, `--stdin-filepath=${target}`], {
  cwd: repository,
  input: header + bundled,
  encoding: 'utf8',
})

let current = ''
try {
  current = readFileSync(target, 'utf8')
} catch {
  // Not written yet.
}
if (current === text) process.exit(0)
if (check) {
  console.error(`${target} is out of date; run node packages/sdk/scripts/extractor-module.mjs`)
  process.exit(1)
}
writeFileSync(target, text)
