// Local documentation search and reading: every Markdown file in the workspace, ranked by simple term scoring.
import {headings, parseFrontMatter, plain, title} from './markdown.ts'
import {readText, walk} from './repo.ts'

export interface Doc {
  path: string
  title: string
  description: string | undefined
  text: string
}

/** Markdown outside dependencies, build output and test fixtures. */
export function loadDocs(root: string): Doc[] {
  return walk(root, '.', path => path.endsWith('.md') && !/(^|\/)(fixtures|snapshots|golden|notices)\//.test(path)).map(path => {
    const text = readText(root, path) ?? ''
    return {path, title: title(text) ?? path, description: parseFrontMatter(text).data.description, text}
  })
}

export interface Hit {
  path: string
  title: string
  section: string | undefined
  line: number
  snippet: string
  score: number
}

function terms(query: string): string[] {
  return [
    ...new Set(
      query
        .toLowerCase()
        .split(/[^\p{L}\p{N}_.-]+/u)
        .filter(term => term.length > 1),
    ),
  ]
}

function count(haystack: string, needle: string): number {
  let found = 0
  for (let index = haystack.indexOf(needle); index >= 0; index = haystack.indexOf(needle, index + needle.length)) found++
  return found
}

/**
 * Scores each document: title and path matches weigh most, then headings and the description, then body term
 * frequency (capped so one long page can't win on repetition). Every query term must appear somewhere. The hit points
 * at the best-matching section.
 */
export function search(docs: readonly Doc[], query: string, limit = 8): Hit[] {
  const wanted = terms(query)
  if (!wanted.length) return []
  const phrase = query.trim().toLowerCase()
  const hits: Hit[] = []
  for (const doc of docs) {
    const lower = doc.text.toLowerCase()
    if (!wanted.every(term => lower.includes(term) || doc.path.toLowerCase().includes(term))) continue
    const titleLower = doc.title.toLowerCase()
    const sections = headings(doc.text)
    let score = 0
    for (const term of wanted) {
      if (titleLower.includes(term)) score += 12
      if (doc.path.toLowerCase().includes(term)) score += 6
      if (doc.description?.toLowerCase().includes(term)) score += 5
      score += Math.min(sections.filter(heading => heading.text.toLowerCase().includes(term)).length, 3) * 3
      score += Math.min(count(lower, term), 20) * 0.5
    }
    if (wanted.length > 1 && lower.includes(phrase)) score += 10
    // Generated reference pages repeat their sources' words; prefer the authored page when scores are close.
    if (lower.startsWith('<!-- generated by')) score *= 0.8
    const lines = doc.text.split('\n')
    let best = {line: 1, score: -1}
    lines.forEach((line, index) => {
      const lineLower = line.toLowerCase()
      const lineScore = wanted.filter(term => lineLower.includes(term)).length + (lineLower.includes(phrase) ? wanted.length : 0)
      if (lineScore > best.score) best = {line: index + 1, score: lineScore}
    })
    const section = [...sections].reverse().find(heading => heading.line <= best.line)
    hits.push({
      path: doc.path,
      title: doc.title,
      section: section && section.level > 1 ? section.text : undefined,
      line: best.line,
      snippet: snippet(plain(lines[best.line - 1] ?? ''), wanted),
      score: Math.round(score * 10) / 10,
    })
  }
  return hits.sort((a, b) => b.score - a.score || a.path.localeCompare(b.path)).slice(0, limit)
}

function snippet(line: string, wanted: string[], width = 160): string {
  if (line.length <= width) return line
  const lower = line.toLowerCase()
  const at = Math.max(0, Math.min(...wanted.map(term => lower.indexOf(term)).filter(index => index >= 0)) - 40)
  return `${at > 0 ? '…' : ''}${line.slice(at, at + width)}${at + width < line.length ? '…' : ''}`
}

/** Finds a document by path (exact, or a unique suffix), else by title (exact, then a unique substring). */
export function findDoc(docs: readonly Doc[], target: string): {doc?: Doc; candidates: Doc[]} {
  const normalized = target.replace(/^\.\//, '').toLowerCase()
  const exactPath = docs.find(doc => doc.path.toLowerCase() === normalized || doc.path.toLowerCase() === `${normalized}.md`)
  if (exactPath) return {doc: exactPath, candidates: []}
  const suffix = docs.filter(
    doc => doc.path.toLowerCase().endsWith(`/${normalized}`) || doc.path.toLowerCase().endsWith(`/${normalized}.md`),
  )
  if (suffix.length === 1) return {doc: suffix[0]!, candidates: []}
  const exactTitle = docs.filter(doc => doc.title.toLowerCase() === normalized)
  if (exactTitle.length === 1) return {doc: exactTitle[0]!, candidates: []}
  const partial = docs.filter(doc => doc.title.toLowerCase().includes(normalized))
  if (partial.length === 1) return {doc: partial[0]!, candidates: []}
  return {candidates: [...suffix, ...exactTitle, ...partial].slice(0, 8)}
}
