import assert from 'node:assert/strict'
import {fileURLToPath} from 'node:url'
import test from 'node:test'
import {generatorFor, generators, generatorsAffectedBy, markedFiles, outputFiles, walkAll} from '../src/lib/generated.ts'
import {globToRegExp, matches, workspaceRoot} from '../src/lib/repo.ts'

const fixture = fileURLToPath(new URL('fixtures/repo/', import.meta.url))

test('globs: * stays in a segment, ** crosses them', () => {
  assert.ok(matches('docs/reference/cli.md', ['docs/reference/**/*.md']))
  assert.ok(matches('docs/reference/schemas/api.md', ['docs/reference/**/*.md']))
  assert.ok(!matches('docs/agents/x/y.md', ['docs/agents/*.md']))
  assert.ok(matches('packages/extractors/a/tests/fixtures/expected/b.json', ['packages/extractors/*/tests/fixtures/expected/**']))
  assert.ok(globToRegExp('a.b').test('a.b') && !globToRegExp('a.b').test('axb'))
})

test('a file is marked generated by a first-line comment saying so', () => {
  assert.deepEqual(markedFiles(fixture), ['gen/out.ts'])
})

test('every generator has a unique name, outputs, inputs and a way to run it', () => {
  assert.equal(new Set(generators.map(generator => generator.name)).size, generators.length)
  for (const generator of generators) {
    assert.ok(generator.outputs.length && generator.inputs.length && generator.generate.length, generator.name)
    assert.ok(generator.check.mode !== 'none' || generator.check.reason, `${generator.name} says why it can't be checked`)
    if (generator.fix)
      assert.ok(
        !generator.needs.some(need => ['network', 'browser', 'toolchains'].includes(need)),
        `${generator.name} can't be part of tools fix`,
      )
  }
})

test("the registry matches this repository: each generator's outputs exist, and every marked file is registered", () => {
  const files = walkAll(workspaceRoot)
  for (const generator of generators)
    assert.ok(outputFiles(workspaceRoot, generator, files).length > 0, `${generator.name} matches no committed file`)
  const unregistered = markedFiles(
    workspaceRoot,
    files.filter(path => !/(^|\/)fixtures\//.test(path)),
  ).filter(path => !generatorFor(path))
  assert.deepEqual(unregistered, [], 'register these in tools/cli/src/lib/generated.ts')
})

test('lookups: the generator of a file, and those whose inputs changed', () => {
  assert.equal(generatorFor('docs/reference/cli.md')?.name, 'reference-docs')
  assert.equal(generatorFor('packages/host/vscode-ui/src/icons.generated.ts')?.name, 'codicon-tokens')
  assert.equal(generatorFor('docs/guide.md'), undefined)
  assert.deepEqual(
    generatorsAffectedBy(['packages/schemas/src/typebox/index.ts']).map(generator => generator.name),
    ['reference-docs', 'builtin-docs', 'schemas'],
  )
  assert.equal(generatorFor('docs/builtins/extractors/repository-map.md')?.name, 'builtin-docs')
  assert.deepEqual(generatorsAffectedBy(['docs/guide.md']), [])
})
