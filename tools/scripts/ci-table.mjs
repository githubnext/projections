#!/usr/bin/env node
// Writes docs/maintainers/ci-plan.md: what CI runs for each case of tools/cli/test/ci-plan.cases.json, by the plan of
// .github/ci-rules.json (tools/cli/src/lib/ci-plan.ts), so a person can see what runs for what without reading the
// rules. The tools package's tests fail when it is stale.
//
//   node tools/scripts/ci-table.mjs           write it
//   node tools/scripts/ci-table.mjs --check   fail if it differs from what the cases and rules give
import {readFileSync, writeFileSync} from 'node:fs'
import {join} from 'node:path'
import {fileURLToPath} from 'node:url'
import {repoFacts} from '../cli/src/lib/ci-facts.ts'
import {ciPlan, executions} from '../cli/src/lib/ci-plan.ts'
import {loadCiRules} from '../cli/src/lib/ci-rules.ts'
import {formatMarkdown} from './reference-docs/shared.mjs'

const root = fileURLToPath(new URL('../../', import.meta.url))
const output = 'docs/maintainers/ci-plan.md'
const facts = repoFacts(root)
const rules = loadCiRules(root)
const {cases} = JSON.parse(readFileSync(join(root, 'tools/cli/test/ci-plan.cases.json'), 'utf8'))

const short = suite => suite.replace(/^packages\//, '').replace(/^tools\//, '')
const counted = (name, count) => (count > 1 ? `${name} ×${count}` : name)

/** What a plan runs, in a phrase: the gated jobs, then the browser suites and their job counts. */
function runs(plan) {
  if (plan.full.length) return 'Everything'
  const checks = executions(plan, rules)
  const jobs = Object.entries(plan.jobs).flatMap(([job, value]) =>
    Array.isArray(value) ? value.map(entry => `${job} (${entry})`) : value ? [job] : [],
  )
  const browser = Object.entries(
    Object.groupBy(
      checks.filter(check => check.job === 'browser'),
      check => check.suites.join(','),
    ),
  )
  const suites = browser.map(([key, items]) => {
    if (items[0].check === 'browser (rest)') return `rest (${items[0].suites.map(short).join(', ')})`
    return counted(short(key), items.length)
  })
  const macos = checks.filter(check => check.job === 'browser-macos').length
  const narrowed = plan.renderers.length ? `; the harness for ${plan.renderers.join(', ')} only` : ''
  return [
    jobs.map(job => `\`${job}\``).join(', ') || 'nothing',
    ...(suites.length ? [`browser: ${suites.join(', ')}${macos ? `, ${macos} on macOS` : ''}${narrowed}`] : []),
  ].join('; ')
}

const rows = cases.map(item => {
  const paths = item.each ? item.files.slice(0, 1) : item.files
  const plan = ciPlan(facts, rules, {paths, event: item.events?.[0] ?? 'pull_request', labels: item.labels ?? []})
  const example = [
    paths.length ? paths.map(path => `\`${path}\``).join(', ') : 'no files',
    ...(item.events ? [`(${item.events[0]})`] : []),
    ...(item.labels ? [`(labels ${item.labels.join(', ')})`] : []),
  ].join(' ')
  return `| ${item.name} | ${example}${item.each && item.files.length > 1 ? ', and each of the others' : ''} | ${runs(plan)} |`
})

const text = [
  '<!-- Generated by tools/scripts/ci-table.mjs from tools/cli/test/ci-plan.cases.json and .github/ci-rules.json. Do not edit: run `node tools/scripts/ci-table.mjs`. -->',
  '',
  '# What CI runs for what',
  '',
  "Each case of the CI planner's table (`tools/cli/test/ci-plan.cases.json`), with what a pull request of that change runs.",
  'A case of several files planned one at a time shows its first. [What CI runs](../../CONTRIBUTING.md#what-ci-runs) explains',
  'the rules, and `npm run tools -- ci explain <files>` explains any change. Every pull request also runs `changes`,',
  '`dollarlint`, `dependency-review`, `advisories` and `ci-ok`.',
  '',
  '| Case | Example | Runs |',
  '| --- | --- | --- |',
  ...rows,
  '',
].join('\n')

// Formatted as the generated reference pages are, so format:check and this check agree.
const formatted = await formatMarkdown(output, text)

if (!process.argv.includes('--check')) writeFileSync(join(root, output), formatted)
else if (readFileSync(join(root, output), 'utf8') !== formatted) {
  console.error(`${output} is stale: run node tools/scripts/ci-table.mjs`)
  process.exit(1)
}
