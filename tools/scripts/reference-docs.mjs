#!/usr/bin/env node
// Generates the reference pages in docs/reference, and the agent prompt files in docs/agents, from the sources they
// describe, so they can't drift:
// action.yml, the JSON Schemas, the renderer SDK's theme tokens, the built renderers' manifests, the CLI's extractor
// catalog, and the SDKs' public APIs, which our own public-API extractors read (typescript-public-api, and
// rust-public-api from rustdoc JSON made with a pinned nightly).
//
//   node tools/scripts/reference-docs.mjs      regenerate every page (npm run docs:generate)
//   node tools/scripts/reference-docs.mjs --check  fail when a page is stale (npm run docs:check)
//   --only NAME[,NAME]                         just these generators, or `tsdoc`: the public API's documentation
//                                              comments (npm run check:tsdoc; tools/scripts/reference-docs/tsdoc.mjs)
//
// Either way, a public TypeScript symbol without a documentation comment fails, as `file:line: message`.
//   --nightly                                  print the pinned nightly the Rust SDK pages need
//
// Run `npm run build` first: tokens and renderers come from built packages. The CLI is built with Cargo.
import {mkdir, readFile, readdir, rm, writeFile} from 'node:fs/promises'
import {dirname, join} from 'node:path'
import {action} from './reference-docs/action.mjs'
import {agents, agentsDir} from './reference-docs/agents.mjs'
import {builtins, missingPages} from './reference-docs/builtins.mjs'
import {cli} from './reference-docs/cli.mjs'
import {extractors} from './reference-docs/extractors.mjs'
import {rendererSdk} from './reference-docs/renderer-sdk.mjs'
import {renderers} from './reference-docs/renderers.mjs'
import {rustApi} from './reference-docs/rust-sdk.mjs'
import {schemas} from './reference-docs/schemas.mjs'
import {GenerationError, fail, generator, nightly, outDir, root} from './reference-docs/shared.mjs'
import {tokens} from './reference-docs/tokens.mjs'
import {publicApiDocs} from './reference-docs/tsdoc.mjs'

const generators = {agents, cli, action, schemas, tokens, renderers, extractors, 'renderer-sdk': rendererSdk, 'rust-sdk': rustApi, builtins}

async function generated() {
  const pages = new Map()
  const files = async directory => {
    const found = []
    let entries
    try {
      entries = await readdir(join(root, directory), {withFileTypes: true})
    } catch {
      return found
    }
    for (const entry of entries) {
      const path = `${directory}/${entry.name}`
      if (entry.isDirectory()) found.push(...(await files(path)))
      else if (entry.name.endsWith('.md')) found.push(path)
    }
    return found
  }
  for (const file of [...(await files(outDir)), ...(await files(agentsDir))]) {
    const text = await readFile(join(root, file), 'utf8')
    if (text.startsWith(`<!-- Generated by ${generator}`)) pages.set(file, text)
  }
  return pages
}

const args = process.argv.slice(2)
// CI installs the toolchain this prints before `--check`.
if (args.includes('--nightly')) {
  console.log(nightly)
  process.exit(0)
}
const checking = args.includes('--check')
const onlyIndex = args.indexOf('--only')
const only = onlyIndex >= 0 ? new Set(args[onlyIndex + 1]?.split(',')) : undefined
// Not a generator: it reads the same sources the API pages do and fails when a public symbol is undocumented.
const checks = {tsdoc: publicApiDocs}
for (const name of only ?? [])
  if (!(name in generators) && !(name in checks))
    fail(`Unknown generator ${name}; one of ${[...Object.keys(generators), ...Object.keys(checks)].join(', ')}`)

async function documentation() {
  const {problems, coverage} = await checks.tsdoc()
  const total = coverage.reduce((sum, workspace) => sum + workspace.documented + workspace.undocumented, 0)
  if (problems.length) {
    for (const problem of problems) console.error(`${problem.file}:${problem.line}: ${problem.message}`)
    console.error(
      `${problems.length} of ${total} public symbols have no documentation comment. Document each one (see CONTRIBUTING.md, Documentation comments), or mark one exported only for tests or tooling \`@internal\`.`,
    )
    process.exitCode = 1
  } else console.log(`${total} public symbols in ${coverage.length} workspaces are documented.`)
}

async function pages() {
  const produced = new Map()
  for (const [name, generate] of Object.entries(generators)) {
    if (only && !only.has(name)) continue
    for (const [file, text] of Object.entries(await generate())) produced.set(file, text)
  }
  const existing = await generated()
  // Pages from generators not run this time are kept; with every generator, a page none produces is stale.
  const extra = only ? [] : [...existing.keys()].filter(file => !produced.has(file))
  const current = async file => existing.get(file) ?? (await readFile(join(root, file), 'utf8').catch(() => undefined))
  const changed = []
  for (const [file, text] of produced) if ((await current(file)) !== text) changed.push(file)
  if (checking) {
    if (changed.length || extra.length) {
      console.error(
        `Generated reference pages are stale:\n${[...changed, ...extra.map(file => `${file} (no longer generated)`)]
          .map(file => `  ${file}`)
          .join('\n')}\nRun \`npm run docs:generate\` and commit the result.`,
      )
      process.exitCode = 1
    } else console.log(`${produced.size} generated reference pages are up to date.`)
  } else {
    for (const file of changed) {
      await mkdir(dirname(join(root, file)), {recursive: true})
      await writeFile(join(root, file), produced.get(file))
    }
    for (const file of extra) await rm(join(root, file))
    console.log(`Generated ${produced.size} reference pages (${changed.length} changed, ${extra.length} removed).`)
  }
  if (missingPages.length) {
    console.error(
      `Every built-in needs a page (see docs/builtins/README.md, Writing a page); missing:\n${missingPages.map(file => `  ${file}`).join('\n')}`,
    )
    process.exitCode = 1
  }
}

try {
  if (!only || only.has('tsdoc')) await documentation()
  if (!only || Object.keys(generators).some(name => only.has(name))) await pages()
} catch (error) {
  if (!(error instanceof GenerationError)) throw error
  console.error(error.message)
  process.exitCode = 1
}
