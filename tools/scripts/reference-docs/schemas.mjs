// The JSON Schema reference pages, from the generated schemas.
import {readFile, readdir} from 'node:fs/promises'
import {join} from 'node:path'
import {code, header, outDir, root, sentence, table, to} from './shared.mjs'

/** Reference pages that end with real examples of what they describe. */
const comparatorExamples = from => `## Examples

[Custom comparators: what they make possible](${to('docs/guides/comparators.md', from)}) shows comparisons made by real
comparators, each drawn beside the default comparison of the same change:

- [Domain verdicts](${to('docs/guides/comparators.md', from)}#domain-verdicts-runtime-security-policies): runtime security
  policy changes interpreted as Scope broadened, Newly enforced and No longer covered.
- [Classification](${to('docs/guides/comparators.md', from)}#classification-api-compatibility): API changes classified as
  breaking, additive or compatible, which a workflow can gate on.
- [Identity](${to('docs/guides/comparators.md', from)}#identity-renames-moves-splits-and-merges): a component moved between
  modules declared as one item, not one removed and another added.
- [Order](${to('docs/guides/comparators.md', from)}#order-telling-the-change-in-the-right-sequence): steps told by severity
  instead of by structure.
`

export async function schemas() {
  // Generated by the schemas package: `<name>/v<version>.json`, where a name may itself have segments.
  const directory = 'packages/schemas/schemas'
  const files = (await readdir(join(root, directory), {recursive: true}))
    .map(file => file.split('\\').join('/'))
    .filter(file => /(?:^|\/)v\d+\.json$/.test(file))
    .sort()
  const loaded = await Promise.all(
    files.map(async file => {
      const [, path, version] = /^(.+)\/v(\d+)\.json$/.exec(file)
      return {
        file,
        name: `${path.replaceAll('/', '-')}${version === '0' ? '' : `-v${version}`}`,
        schema: JSON.parse(await readFile(join(root, directory, file), 'utf8')),
      }
    }),
  )
  const byId = new Map(loaded.map(entry => [entry.schema.$id, entry]))
  const title = schema => {
    const text = String(schema.title ?? '')
      .replace(/^Projections\s+/, '')
      .replace(/\s+v\d+$/, '')
    return text.charAt(0).toUpperCase() + text.slice(1)
  }
  const pages = {}
  for (const entry of loaded) {
    const {schema, name, file} = entry
    const ref = target => {
      const [id, pointer] = target.split('#')
      const local = id === '' || id === schema.$id
      const other = local ? undefined : byId.get(id)
      if (!local && !other) return code(target)
      const definition = pointer?.match(/^\/\$defs\/(.+)$/)?.[1]
      const base = local ? '' : `${other.name}.md`
      if (definition) return `[${code(definition)}](${base}#${definition.toLowerCase()})`
      return local ? `[the document](#document)` : `[${title(other.schema)}](${base})`
    }
    const type = (value, depth = 0) => {
      if (!value || typeof value !== 'object') return value === true ? 'any' : 'never'
      if (value.$ref) return ref(value.$ref)
      if ('const' in value) return code(JSON.stringify(value.const))
      if (value.enum) return value.enum.map(item => code(JSON.stringify(item))).join(' or ')
      for (const keyword of ['oneOf', 'anyOf']) if (value[keyword]) return value[keyword].map(item => type(item, depth)).join(' or ')
      if (value.allOf) return value.allOf.map(item => type(item, depth)).join(' and ')
      const types = Array.isArray(value.type) ? value.type : value.type ? [value.type] : []
      const described = types.map(kind => {
        if (kind === 'array') return value.items ? `array of ${type(value.items, depth + 1)}` : 'array'
        if (kind === 'object' && !value.properties && value.additionalProperties && typeof value.additionalProperties === 'object') {
          return `map of ${type(value.additionalProperties, depth + 1)}`
        }
        return kind
      })
      return described.join(' or ') || (value.properties ? 'object' : 'any')
    }
    const constraints = value => {
      const parts = []
      if (value.pattern) parts.push(`Pattern ${code(value.pattern)}.`)
      if (value.format) parts.push(`Format ${code(value.format)}.`)
      const plural = (count, noun) => `${count} ${noun}${count === 1 ? '' : 's'}`
      for (const [keyword, label] of [
        ['minLength', count => `At least ${plural(count, 'character')}`],
        ['maxLength', count => `At most ${plural(count, 'character')}`],
        ['minimum', count => `At least ${count}`],
        ['maximum', count => `At most ${count}`],
        ['exclusiveMinimum', count => `More than ${count}`],
        ['minItems', count => `At least ${plural(count, 'item')}`],
        ['maxItems', count => `At most ${plural(count, 'item')}`],
        ['minProperties', count => `At least ${plural(count, 'property').replace('propertys', 'properties')}`],
        ['maxProperties', count => `At most ${plural(count, 'property').replace('propertys', 'properties')}`],
      ]) {
        if (value[keyword] !== undefined) parts.push(`${label(value[keyword])}.`)
      }
      if (value.uniqueItems) parts.push('Items are unique.')
      if (value.default !== undefined) parts.push(`Default ${code(JSON.stringify(value.default))}.`)
      return parts.join(' ')
    }
    // Properties of an object, with nested inline objects as dotted rows.
    const rows = (value, prefix = '', depth = 0) => {
      const required = new Set(value.required ?? [])
      return Object.entries(value.properties ?? {}).flatMap(([property, definition]) => {
        const path = `${prefix}${property}`
        const row = [
          code(path),
          type(definition),
          required.has(property) ? 'Yes' : '',
          [sentence(definition.description), constraints(definition)].filter(Boolean).join(' '),
        ]
        const nested = definition.properties && depth < 3 ? rows(definition, `${path}.`, depth + 1) : []
        return [row, ...nested]
      })
    }
    const describe = value => {
      const parts = []
      if (value.properties) {
        parts.push(table(['Property', 'Type', 'Required', 'Description'], rows(value)))
        if (value.additionalProperties === false) parts.push('No other properties are allowed.')
        else if (value.additionalProperties && typeof value.additionalProperties === 'object') {
          parts.push(`Other properties: ${type(value.additionalProperties)}.`)
        }
      } else {
        const notes = constraints(value)
        parts.push(`Type: ${type(value)}.${notes ? ` ${notes}` : ''}`)
      }
      if (value.if || value.dependentRequired || value.dependentSchemas) {
        parts.push('Further rules depend on these values; see the JSON Schema for them.')
      }
      return parts.join('\n\n')
    }
    // A domain schema's refinement: the typed `data` fields of each collection and kind.
    const typedData = refinement => {
      const sections = ['entities', 'relationships'].flatMap(collection => {
        const items = refinement.properties?.[collection]?.items
        if (!items) return []
        const rules = (items.allOf ?? [items]).map(rule =>
          rule.if ? {kinds: rule.if.properties.kind.enum, item: rule.then} : {kinds: undefined, item: rule},
        )
        const fieldRows = rules.flatMap(({kinds, item}) => {
          const data = item.properties?.data ?? {}
          const required = new Set(data.required ?? [])
          return Object.entries(data.properties ?? {}).map(([field, definition]) => [
            kinds ? kinds.map(kind => code(kind)).join(', ') : 'Every kind',
            code(`data.${field}`),
            type(definition),
            required.has(field) ? 'Yes' : '',
            [sentence(definition.description), constraints(definition)].filter(Boolean).join(' '),
          ])
        })
        return [
          `### ${collection === 'entities' ? 'Entities' : 'Relationships'}\n\n${table(['Kind', 'Field', 'Type', 'Required', 'Description'], fieldRows)}`,
        ]
      })
      return sections.length
        ? `The engine checks every typed field, and reports a violation at its path. Other \`data\` fields are open JSON.\n\n${sections.join('\n\n')}`
        : 'No typed `data` fields: every `data` field is open JSON.'
    }
    if (schema.$defs?.refinement) {
      pages[`${outDir}/schemas/${name}.md`] = `${header([`${directory}/${file}`])}# ${title(schema)}

${sentence(schema.description)} The schema is published at its ID, ${code(schema.$id)}; it is generated from TypeBox
definitions into [${code(`${directory}/${file}`)}](${to(`${directory}/${file}`, `${outDir}/schemas`)}).

${
  schema.$defs.refinement.properties.schema.const
    ? `An extraction in this schema is an [extraction](extraction.md) whose \`schema\` is ${code(schema.$defs.refinement.properties.schema.const)}; the extraction schema applies this one
to it.`
    : `An extraction follows this vocabulary when its \`vocabularies\` include it; its \`schema\` must be ${schema.$defs.refinement.properties.schema.enum.map(code).join(' or ')}. The extraction schema applies this one to it.`
}

## Typed data

${typedData(schema.$defs.refinement)}
${(() => {
  // The records typed fields refer to, such as api/v0's contract facts.
  const records = Object.entries(schema.$defs).filter(([definition]) => definition !== 'refinement')
  return records.length
    ? `\n## Definitions\n\n${records
        .map(
          ([definition, value]) =>
            `### ${code(definition)}\n\n${[sentence(value.description), describe(value)].filter(Boolean).join('\n\n')}`,
        )
        .join('\n\n')}\n`
    : ''
})()}`
      continue
    }
    const definitions = Object.entries(schema.$defs ?? {})
    const examples = name === 'comparison' ? `\n${comparatorExamples(`${outDir}/schemas`)}` : ''
    pages[`${outDir}/schemas/${name}.md`] = `${header([`${directory}/${file}`])}# ${title(schema)}

${sentence(schema.description)} The schema is published at its ID, ${code(schema.$id)}; it is generated from TypeBox
definitions into [${code(`${directory}/${file}`)}](${to(`${directory}/${file}`, `${outDir}/schemas`)}).

## Document

${describe(schema)}
${
  definitions.length
    ? `\n## Definitions\n\n${definitions
        .map(
          ([definition, value]) =>
            `### ${code(definition)}\n\n${[sentence(value.description), describe(value)].filter(Boolean).join('\n\n')}`,
        )
        .join('\n\n')}\n`
    : ''
}${examples}`
  }
  pages[`${outDir}/schemas/README.md`] = `${header([`${directory}/**/v*.json`])}# Schemas

The documents Projections reads and writes, as JSON Schema (draft 2020-12), published at
\`https://schemas.projections.githubnext.com/\`. An ID names a major version, which changes only additively; each
release also publishes an immutable snapshot, \`<name>/v<major>/<release>.json\`, to pin
([versioning](${to('docs/contracts.md', `${outDir}/schemas`)}#versioning-and-publishing)). [Extractions and comparisons](${to('docs/guides/schemas.md', `${outDir}/schemas`)}#extraction-schema) explains the
domain schemas an extraction's \`schema\` field selects.

${table(
  ['Schema', 'ID', 'Describes'],
  loaded.map(({schema, name}) => [`[${title(schema)}](${name}.md)`, code(schema.$id), sentence(schema.description)]),
)}
`
  return pages
}
