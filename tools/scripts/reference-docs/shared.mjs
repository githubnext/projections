import {join, posix} from 'node:path'
import {fileURLToPath, pathToFileURL} from 'node:url'
import {format} from 'oxfmt'

export const root = fileURLToPath(new URL('../../../', import.meta.url))
export const outDir = 'docs/reference'
export const generator = 'tools/scripts/reference-docs.mjs'
/** The nightly the rust-public-api extractor's tests and README use; the format must be one it reads. */
export const nightly = 'nightly-2026-09-17'

export class GenerationError extends Error {}
export const fail = message => {
  throw new GenerationError(message)
}
/** A link from a page in `from` (docs/reference by default) to a repository file. */
export const to = (path, from = outDir) => posix.relative(from, path)
export const header = sources =>
  `<!-- Generated by ${generator} from ${sources.join(', ')}. Do not edit: run \`npm run docs:generate\`. -->\n\n`
export const cell = value =>
  String(value ?? '')
    .replace(/\s*\n\s*/g, ' ')
    .replace(/\|/g, '\\|')
    .trim()
export const code = value => {
  const text = String(value)
  const fence = text.includes('`') ? '``' : '`'
  return `${fence}${text.includes('`') ? ` ${text} ` : text}${fence}`
}
export const table = (headings, rows) =>
  [`| ${headings.join(' | ')} |`, `|${headings.map(() => '---').join('|')}|`, ...rows.map(row => `| ${row.map(cell).join(' | ')} |`)].join(
    '\n',
  )
export const sentence = text => {
  const value = String(text ?? '').trim()
  return value && !/[.!?]$/.test(value) ? `${value}.` : value
}
export const json = value => `\`\`\`json\n${JSON.stringify(value, null, 2)}\n\`\`\``

export async function exists(path) {
  try {
    return await stat(join(root, path))
  } catch {
    return undefined
  }
}
export function run(command, args, options = {}) {
  const result = spawnSync(command, args, {cwd: root, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, ...options})
  if (result.error) fail(`${command} ${args.join(' ')}: ${result.error.message}`)
  if (result.status !== 0) fail(`${command} ${args.join(' ')} exited with ${result.status}:\n${result.stderr.trim()}`)
  return result.stdout
}
export async function requireBuilt(path) {
  if (!(await exists(path))) fail(`${path} is missing; run \`npm run build\` first`)
  return pathToFileURL(join(root, path)).href
}

let binary
/** The CLI: PROJECTIONS_BIN, or this checkout's, built with Cargo when needed. */
export function projections() {
  if (binary) return binary
  if (process.env.PROJECTIONS_BIN) return (binary = process.env.PROJECTIONS_BIN)
  run('cargo', ['build', '--quiet', '--locked', '-p', 'projections-cli'], {stdio: ['ignore', 'ignore', 'pipe']})
  return (binary = join(root, 'target', 'debug', process.platform === 'win32' ? 'projections.exe' : 'projections'))
}

/** Runs one built-in extractor through the public extractor process protocol: a request on stdin, an extraction out. */
export function extract(extractor, inputs, {repository = root, trusted = false} = {}) {
  const commit = run('git', ['rev-parse', 'HEAD']).trim()
  const request = {
    protocolVersion: 0,
    projection: {id: 'reference', definition: {id: 'reference', extractor, renderer: 'api', inputs}},
    repository: {root: repository, checkout: repository, revision: {kind: 'working-tree', ref: 'working-tree', commit, dirty: true}},
    capabilities: {trusted, network: false},
  }
  return JSON.parse(run(projections(), ['__extract', extractor], {input: JSON.stringify(request)}))
}

