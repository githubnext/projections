/** The built renderers in packages/renderers/*, by directory name: each one's package.json and built renderer.json. */
export async function builtRenderers() {
  const found = []
  for (const directory of (await readdir(join(root, 'packages/renderers'))).sort()) {
    const manifestPath = `packages/renderers/${directory}/package.json`
    if (!(await exists(manifestPath))) continue
    const pkg = JSON.parse(await readFile(join(root, manifestPath), 'utf8'))
    if (!pkg.projections?.renderer) continue
    const bundle = `packages/renderers/${directory}/${pkg.projections.renderer}/renderer.json`
    await requireBuilt(bundle)
    found.push({directory, pkg, manifest: JSON.parse(await readFile(join(root, bundle), 'utf8'))})
  }
  return found
}

const ignoreMarker = '<!-- prettier-ignore -->'
const delimiterRow = /^\s*\|?\s*:?-+:?\s*(\|\s*:?-+:?\s*)*\|?\s*$/
const tableCells = line =>
  line
    .trim()
    .replace(/^\|/, '')
    .replace(/(?<!\\)\|$/, '')
    .split(/(?<!\\)\|/)
    .map(cell => cell.trim())

/**
 * Marks each table whose aligned form would be wider than 140 columns so the formatter keeps it compact, as the
 * hand-written docs do (docs/maintainers/file-standards.md).
 */
export function markWideTables(text) {
  const lines = text.split('\n')
  const out = []
  let fenced = false
  for (let index = 0; index < lines.length;) {
    const line = lines[index]
    if (/^\s*(```|~~~)/.test(line)) fenced = !fenced
    if (fenced || !line.trimStart().startsWith('|') || !delimiterRow.test(lines[index + 1] ?? '')) {
      out.push(line)
      index++
      continue
    }
    let end = index
    while (end < lines.length && lines[end].trimStart().startsWith('|')) end++
    const rows = lines
      .slice(index, end)
      .filter((_, row) => row !== 1)
      .map(tableCells)
    const columns = Math.max(...rows.map(row => row.length))
    const widths = Array.from({length: columns}, (_, column) => Math.max(3, ...rows.map(row => row[column]?.length ?? 0)))
    const width = widths.reduce((sum, value) => sum + value, 0) + 3 * columns + 1
    if (width > 140 && out.at(-1)?.trim() !== ignoreMarker) out.push(`${/^\s*/.exec(line)[0]}${ignoreMarker}`)
    out.push(...lines.slice(index, end))
    index = end
  }
  return out.join('\n')
}

/** Markdown as `npm run format` leaves it (`.oxfmtrc.json`), so a page with generated regions stays formatted. */
export async function formatMarkdown(file, text) {
  const config = JSON.parse(await readFile(join(root, '.oxfmtrc.json'), 'utf8'))
  const options = Object.fromEntries(Object.entries(config).filter(([key]) => !['$schema', 'ignorePatterns', 'overrides'].includes(key)))
  for (const override of config.overrides ?? [])
    if (override.files.some(glob => posix.matchesGlob(file, glob))) Object.assign(options, override.options)
  const formatted = await format(file, markWideTables(text), options)
  if (formatted.errors.length) fail(`${file}: ${formatted.errors[0].message}`)
  return formatted.code
}
